/** Runtime fields only. The complete catalogue remains the source of truth. */
export function renderCatalogIndex(metrics, sourceHash) {
  const rows = metrics.map(({ id, name, category, scope, parameterIds, audio }) => ({
    id, name, category, scope, parameterIds,
    audio: { viability: audio.viability, condition: audio.condition },
  }));
  return `/** Generated by scripts/generate-catalog-index.mjs; do not edit by hand. */
import type { NarratedMetricDefinition } from './catalog.js';

/** The engine and selectors need this index, not the full evidence and documentation. */
export type NarratedMetricSummary = Pick<NarratedMetricDefinition, 'id' | 'name' | 'category' | 'scope' | 'parameterIds'> & {
  audio: Pick<NarratedMetricDefinition['audio'], 'viability' | 'condition'>;
};
export const NARRATED_CATALOG_SOURCE_SHA256 = ${JSON.stringify(sourceHash)};
export const NARRATED_METRICS: NarratedMetricSummary[] = [
${rows.map(row => `  ${JSON.stringify(row)},`).join('\n')}
];
export const NARRATED_METRIC_BY_ID: ReadonlyMap<string, NarratedMetricSummary> = new Map(NARRATED_METRICS.map(metric => [metric.id, metric]));
`.replace(/\r?\n/g, '\r\n');
}
